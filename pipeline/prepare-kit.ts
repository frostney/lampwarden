// Turns the kit (pipeline/kit/kit.ts, TypeScript with exports) into the plain JavaScript that QuickJS runs, and writes it
// as pipeline/prepared-kit.ts so a server function and a browser worker can carry it as a string: neither has Bun's
// transpiler or a file system to strip types with at run time. `bun run kit` calls this after assembling the kit;
// prepare-kit.test.ts fails when the committed file no longer matches the kit.
//
// The kit is a single file with no imports, so there is no bundler step: types are stripped, `export` is dropped from
// its declarations, and the exported names are returned from a function by `kitScript`.
import { createHash } from "node:crypto";
import type { PreparedKit } from "./quickjs-core";

const IDENTIFIER = /^[A-Za-z_]\w*$/;

export function sha256Text(text: string): string {
  return createHash("sha256").update(text).digest("hex");
}

/** The kit as plain JavaScript statements and the names it exports. Runs under Bun (its transpiler strips the types). */
export function prepareKitSource(source: string): PreparedKit {
  const body = new Bun.Transpiler({ loader: "ts" }).transformSync(source).replace(/^export\s+/gm, "");
  const names = [...source.matchAll(/^export (?:const|let|function|class) (\w+)/gm)].map((match) => match[1] ?? "");
  // every value export must have been found, or build code calling it would fail with a ReferenceError
  const valueExports = (source.match(/^export (?!type\b|interface\b)/gm) ?? []).length;
  if (valueExports !== names.length) throw new Error("kit.ts has an export form the QuickJS renderers do not handle");
  return { sha256: sha256Text(source), names: names.filter((name) => IDENTIFIER.test(name)), body };
}

/** The source of pipeline/prepared-kit.ts. */
export function preparedKitModule(prepared: PreparedKit): string {
  return [
    "// GENERATED by `bun run kit` (pipeline/prepare-kit.ts) from pipeline/kit/kit.ts. Do not edit.",
    "// The kit as plain JavaScript for QuickJS, which runs model-written builds on the server and in the browser.",
    'import type { PreparedKit } from "./quickjs-core";',
    "",
    "export const PREPARED_KIT: PreparedKit = {",
    `  sha256: ${JSON.stringify(prepared.sha256)},`,
    `  names: ${JSON.stringify(prepared.names)},`,
    `  body: ${JSON.stringify(prepared.body)},`,
    "};",
    "",
  ].join("\n");
}
