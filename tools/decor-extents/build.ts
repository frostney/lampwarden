// Writes src/scene/decor-extents.ts: where each committed sprite's pixels are, for the decor placer.
// usage: bun tools/decor-extents/build.ts      (or `bun run decor`) after adding or redrawing a sprite
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { measureCommittedSprites, repositoryRoot } from "./measure";

const measured = measureCommittedSprites();
const entries = Object.entries(measured).map(
  ([key, extents]) => `  ${JSON.stringify(key)}: ${JSON.stringify(extents)},`,
);
const target = join(repositoryRoot, "src/scene/decor-extents.ts");
writeFileSync(
  target,
  `// Generated by tools/decor-extents/build.ts (bun run decor) from public/sprites/*.png: do not edit by hand.
// Each sprite's base hulls and whole-sprite box in pixels from its anchor (src/scene/extent.ts).
import type { SpriteExtents } from "./extent";

export const SPRITE_EXTENTS: Record<string, SpriteExtents> = {
${entries.join("\n")}
};
`,
);
const formatted = Bun.spawnSync(["bunx", "biome", "format", "--write", target], { cwd: repositoryRoot });
if (!formatted.success) throw new Error(`biome could not format ${target}: ${formatted.stderr.toString()}`);
console.log(`wrote ${Object.keys(measured).length} sprites to src/scene/decor-extents.ts`);
