// Writes src/scene/decor-extents.ts: where the pixels of each sprite the decor placer uses are (PLACED_SPRITES in
// src/scene/decor.ts), measured from public/sprites/*.png.
// usage: bun tools/decor-extents/build.ts            (or `bun run decor`) after adding a decoration or redrawing a placed sprite
//        bun tools/decor-extents/build.ts --check    write nothing; fail when the committed table is not a fresh measurement
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { measurePlacedSprites, repositoryRoot } from "./measure";

const measured = measurePlacedSprites();
const entries = Object.entries(measured).map(
  ([key, extents]) => `  ${JSON.stringify(key)}: ${JSON.stringify(extents)},`,
);
const source = `// Generated by tools/decor-extents/build.ts (bun run decor) from public/sprites/*.png: do not edit by hand.
// The base hulls and whole-sprite box, in pixels from the anchor (src/scene/extent.ts), of each sprite the decor placer
// uses: the lamps and the kinds in DECOR (PLACED_SPRITES in decor.ts). The monsters and the rest are not measured.
import type { SpriteExtents } from "./extent";

export const SPRITE_EXTENTS: Record<string, SpriteExtents> = {
${entries.join("\n")}
};
`;
const targetPath = "src/scene/decor-extents.ts";
const formatted = Bun.spawnSync(["bunx", "biome", "format", `--stdin-file-path=${targetPath}`], {
  cwd: repositoryRoot,
  stdin: Buffer.from(source),
});
if (!formatted.success) {
  throw new Error(`biome could not format ${targetPath}: ${formatted.stderr.toString()}`);
}
const fresh = formatted.stdout.toString();
const target = join(repositoryRoot, targetPath);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== fresh) {
    console.error(`${targetPath} differs from a fresh measurement of the sprites the placer uses; run bun run decor`);
    process.exit(1);
  }
  console.log(`${targetPath}: identical`);
} else {
  writeFileSync(target, fresh);
  console.log(`wrote ${Object.keys(measured).length} sprites to ${targetPath}`);
}
